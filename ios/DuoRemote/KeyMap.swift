import UIKit

/// キーの番号の変換と、よく使うWindowsの仮想キーコード。
enum KeyMap {
    // Windowsの仮想キーコード（iPhoneのキーボードの横に出すキー用）
    static let vkBack = 0x08
    static let vkTab = 0x09
    static let vkReturn = 0x0D
    static let vkShift = 0x10
    static let vkControl = 0x11
    static let vkMenu = 0x12 // Alt
    static let vkEnd = 0x23
    static let vkHome = 0x24
    static let vkLWin = 0x5B
    static let vkEscape = 0x1B
    static let vkLeft = 0x25
    static let vkUp = 0x26
    static let vkRight = 0x27
    static let vkDown = 0x28
    static let vkDelete = 0x2E

    // 日本語キーボードの「かな」「英数」（HIDの LANG1、LANG2）。IMEのオン・オフに使う
    static let hidGrave = 0x35 // ` ~（日本語キーボードでは、半角/全角）
    static let hidLang1 = 0x90
    static let hidLang2 = 0x91

    /// USBキーボードのキーの番号（HID）を、PCのスキャンコードに変える。
    /// 0xE0 が付く拡張キーは、0xE0xx の形で返す。対応していないキーは nil。
    static func scanCode(hid usage: Int) -> Int? {
        switch usage {
        case 0x04...0x1D: // A〜Z
            return letters[usage - 0x04]
        case 0x1E...0x26: // 1〜9
            return usage - 0x1E + 0x02
        case 0x3A...0x43: // F1〜F10
            return usage - 0x3A + 0x3B
        case 0x68...0x72: // F13〜F23（Macのキーボードには F13〜F19 がある）
            return usage - 0x68 + 0x64
        case 0x73: // F24
            return 0x76
        default:
            return others[usage]
        }
    }

    /// 押し続けても繰り返さないキー（Ctrl、Shift、Alt、Windowsキー、Caps Lock）。
    static func isModifier(scanCode sc: Int) -> Bool {
        [0x1D, 0x2A, 0x36, 0x38, 0x3A, 0xE01D, 0xE038, 0xE05B, 0xE05C].contains(sc)
    }

    private static let letters = [
        0x1E, 0x30, 0x2E, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32, // A〜M
        0x31, 0x18, 0x19, 0x10, 0x13, 0x1F, 0x14, 0x16, 0x2F, 0x11, 0x2D, 0x15, 0x2C, // N〜Z
    ]

    private static let others: [Int: Int] = [
        0x27: 0x0B, // 0
        0x28: 0x1C, // Enter
        0x29: 0x01, // Esc
        0x2A: 0x0E, // Backspace
        0x2B: 0x0F, // Tab
        0x2C: 0x39, // スペース
        0x2D: 0x0C, // -
        0x2E: 0x0D, // = （JISでは ^）
        0x2F: 0x1A, // [ （JISでは @）
        0x30: 0x1B, // ] （JISでは [）
        0x31: 0x2B, // \ （JISでは ]）
        0x32: 0x2B, // USキーボード以外の #
        0x33: 0x27, // ;
        0x34: 0x28, // ' （JISでは :）
        0x35: 0x29, // ` （JISでは 半角/全角）
        0x36: 0x33, // ,
        0x37: 0x34, // .
        0x38: 0x35, // /
        0x39: 0x3A, // Caps Lock
        0x44: 0x57, // F11
        0x45: 0x58, // F12
        0x46: 0xE037, // Print Screen
        0x47: 0x46, // Scroll Lock
        0x49: 0xE052, // Insert
        0x4A: 0xE047, // Home
        0x4B: 0xE049, // Page Up
        0x4C: 0xE053, // Delete
        0x4D: 0xE04F, // End
        0x4E: 0xE051, // Page Down
        0x4F: 0xE04D, // →
        0x50: 0xE04B, // ←
        0x51: 0xE050, // ↓
        0x52: 0xE048, // ↑
        0x53: 0x45, // Num Lock
        0x54: 0xE035, // テンキー /
        0x55: 0x37, // テンキー *
        0x56: 0x4A, // テンキー -
        0x57: 0x4E, // テンキー +
        0x58: 0xE01C, // テンキー Enter
        0x59: 0x4F, 0x5A: 0x50, 0x5B: 0x51, // テンキー 1〜3
        0x5C: 0x4B, 0x5D: 0x4C, 0x5E: 0x4D, // テンキー 4〜6
        0x5F: 0x47, 0x60: 0x48, 0x61: 0x49, // テンキー 7〜9
        0x62: 0x52, // テンキー 0
        0x63: 0x53, // テンキー .
        0x64: 0x56, // USキーボード以外の \
        0x65: 0xE05D, // アプリケーションキー
        0x67: 0x59, // テンキー =
        0x87: 0x73, // JIS の ろ（\ _）
        0x88: 0x70, // JIS の カタカナ/ひらがな
        0x89: 0x7D, // JIS の ¥
        0x8A: 0x79, // JIS の 変換
        0x8B: 0x7B, // JIS の 無変換
        0xE0: 0x1D, // 左Ctrl
        0xE1: 0x2A, // 左Shift
        0xE2: 0x38, // 左Alt（Macのキーボードでは option）
        0xE3: 0xE05B, // 左Windowsキー（Macのキーボードでは command）
        0xE4: 0xE01D, // 右Ctrl
        0xE5: 0x36, // 右Shift
        0xE6: 0xE038, // 右Alt
        0xE7: 0xE05C, // 右Windowsキー
    ]
}
